#!/usr/bin/env python3
"""Generate a jsonschema2pojo-friendly JSON Schema (draft-04) from a PIQI model file.

Usage:
  python generate_piqi_schema.py [--model PATH_OR_URL] [--meta PATH_OR_URL]
                                 [--package com.navapbc.piqi.model.clinical] [--out patient.json]

Notes:
  * Simple attributes are emitted as {"type": "string", "existingJavaType": "<package>.PiqiSimpleAttribute"},
    so the JSON stays a plain string while Java gets a PiqiSimpleAttribute type (hand-written class).
  * Cardinality: ONE / ZERO_TO_ONE -> object; *_TO_MANY -> array (minItems 1 for ONE_TO_MANY);
    ONE and ONE_TO_MANY classes are listed as required on the root.
  * Supported attribute types: Simple Attribute, Codeable Concept, Observation Value, Range Value
    (the last two only emit a definition when the model uses them). Anything else raises an error.
  * Data class names are singularized for the element class (e.g. "Lab Results" -> LabResult).
  * Roles in the model file are ignored.
  * Also writes PiqiSimpleAttribute.java (in the same folder as --out) for the chosen package.
  * If the 'jsonschema' package is installed, the model is validated against the meta-schema first.
"""
import argparse, json, os, re, sys, urllib.request

BASE = "https://hl7.org/xprod/ig/uv/piqi/2.0.0-202609-ballot/en/"

def load(src):
    if src.startswith(("http://", "https://")):
        with urllib.request.urlopen(src) as r:
            return json.load(r)
    with open(src, encoding="utf-8") as f:
        return json.load(f)

def clean(s):
    return re.sub(r"\s+", " ", s).strip() if s else None

def singular(word):
    if word.endswith("ies"):
        return word[:-3] + "y"
    if word.endswith("s") and not word.endswith(("ss", "us", "is")):
        return word[:-1]
    return word

def class_name(name):
    words = name.title().split(" ")
    words[-1] = singular(words[-1])
    return re.sub(r"[^A-Za-z0-9]", "", "".join(words))

def build(model, package):
    sa_type = f"{package}.PiqiSimpleAttribute"

    def simple(desc=None):
        p = {"type": "string", "existingJavaType": sa_type}
        if desc:
            p["description"] = desc
        return p

    defs = {
        "Coding": {
            "type": "object", "description": "A single code from a code system.",
            "additionalProperties": False,
            "properties": {
                "code": simple("Code value for the coding"),
                "display": simple("Display value for the coding"),
                "system": simple("Code system identifier for the coding"),
            },
        },
        "CodeableConcept": {
            "type": "object",
            "description": "PIQI Codeable Concept: display text plus zero-to-many codings.",
            "additionalProperties": False,
            "properties": {
                "text": simple("Text representation of the concept"),
                "codings": {"type": "array", "items": {"$ref": "#/definitions/Coding"},
                            "description": "Collection of zero-to-many codings"},
            },
        },
    }
    obs_value = {
        "type": "object",
        "description": "PIQI Observation Value: text, a value type, numeric value(s) and/or coded values.",
        "additionalProperties": False,
        "properties": {
            "text": simple("Text representation of the value"),
            "type": {"$ref": "#/definitions/CodeableConcept"},
            "number": simple("For numeric values"),
            "number2": simple("For second numeric value"),
            "codings": {"type": "array", "items": {"$ref": "#/definitions/Coding"},
                        "description": "Zero-to-many codings representing the value if it is a codeable concept"},
        },
    }
    range_value = {
        "type": "object",
        "description": "PIQI Range Value: a numeric range (not for date ranges).",
        "additionalProperties": False,
        "properties": {
            "text": simple("Text representation of the value range"),
            "lowValue": simple("Text representation of the low value"),
            "highValue": simple("Text representation of the high value"),
        },
    }
    root_props, root_required = {}, []

    for dc in sorted(model["dataClasses"], key=lambda d: d["sequence"]):
        props = {}
        for a in sorted(dc["attributes"], key=lambda x: x["sequence"]):
            t = a["attributeType"]["mnemonic"]
            if a["autoGenerated"] or t in ("CLS", "ELM"):
                continue
            if t == "ATR":
                props[a["fieldName"]] = simple(clean(a["description"]))
            elif t == "CC":
                props[a["fieldName"]] = {"$ref": "#/definitions/CodeableConcept"}
            elif t == "OBSVAL":
                defs.setdefault("ObservationValue", obs_value)
                props[a["fieldName"]] = {"$ref": "#/definitions/ObservationValue"}
            elif t == "RV":
                defs.setdefault("RangedValue", range_value)
                props[a["fieldName"]] = {"$ref": "#/definitions/RangedValue"}
            else:
                raise SystemExit(f"Unsupported attribute type {t} on {a['fieldName']}")
        cn = class_name(dc["name"])
        defs[cn] = {"type": "object",
                    "description": f"PIQI data class: {dc['name']} ({dc['mnemonic']}).",
                    "additionalProperties": False, "properties": props}
        ref = {"$ref": f"#/definitions/{cn}"}
        card = dc["cardinality"]["mnemonic"]
        if card in ("ONE", "ZERO_TO_ONE"):
            prop = ref
        else:
            prop = {"type": "array", "items": ref}
            if card == "ONE_TO_MANY":
                prop["minItems"] = 1
        root_props[dc["fieldName"]] = prop
        if card in ("ONE", "ONE_TO_MANY"):
            root_required.append(dc["fieldName"])

    return {
        "$schema": "http://json-schema.org/draft-04/schema#",
        "description": (f"{model['name']} ({model['mnemonic']} v{model['version']}): {model['description']}. "
                        f"Root entity: {model['rootEntityName']}. "
                        "Generated using the PIQI model meta-schema (piqi-model-schema.json)."),
        "type": "object", "additionalProperties": False,
        "properties": root_props, "required": root_required, "definitions": defs,
    }

SIMPLE_ATTRIBUTE_JAVA = """package {package};

import com.fasterxml.jackson.annotation.JsonCreator;
import com.fasterxml.jackson.annotation.JsonValue;
import java.util.Objects;

/** PIQI Simple Attribute: a single value that is a plain string in the JSON payload. */
public class PiqiSimpleAttribute {{

    private final String value;

    @JsonCreator(mode = JsonCreator.Mode.DELEGATING)
    public PiqiSimpleAttribute(String value) {{
        this.value = value;
    }}

    @JsonValue
    public String getValue() {{
        return value;
    }}

    @Override
    public boolean equals(Object o) {{
        return o instanceof PiqiSimpleAttribute s && Objects.equals(value, s.value);
    }}

    @Override
    public int hashCode() {{
        return Objects.hashCode(value);
    }}

    @Override
    public String toString() {{
        return String.valueOf(value);
    }}
}}
"""

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", default=BASE + "PAT_CLINICAL_V1.json")
    ap.add_argument("--meta", default=BASE + "piqi-model-schema.json")
    ap.add_argument("--package", default="com.navapbc.piqi.model.clinical")
    ap.add_argument("--out", default="patient.json")
    args = ap.parse_args()

    model = load(args.model)
    try:
        from jsonschema import Draft202012Validator
        errors = list(Draft202012Validator(load(args.meta)).iter_errors(model))
        if errors:
            sys.exit("Model fails meta-schema validation:\n" + "\n".join(e.message for e in errors[:10]))
        print("Model passes meta-schema validation.")
    except ImportError:
        print("jsonschema not installed; skipping meta-schema validation.")

    schema = build(model, args.package)
    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(schema, f, indent=2, ensure_ascii=False)
    print(f"Wrote {args.out}")
    java_path = os.path.join(os.path.dirname(os.path.abspath(args.out)), "PiqiSimpleAttribute.java")
    with open(java_path, "w", encoding="utf-8") as f:
        f.write(SIMPLE_ATTRIBUTE_JAVA.format(package=args.package))
    print(f"Wrote {java_path}")

if __name__ == "__main__":
    main()
